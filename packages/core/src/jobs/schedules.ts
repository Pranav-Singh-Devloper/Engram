// The hosted pg_cron schedules (SPEC §6.4), generated from `config` and the
// registry so the SQL never drifts from the engine's parameters. Written to
// supabase/hosted/R__cron_schedules.sql by `pnpm db:hosted-cron`; a test
// fails if the committed file differs from what this generates.
import { config } from '../config/index.js';
import type { EngramConfig } from '../config/index.js';
import { STATIC_PREDICATES } from '../decay/sweep.js';

export const CRON_SCHEDULES_FILE = 'R__cron_schedules.sql';

const literal = (s: string) => `'${s.replace(/'/g, "''")}'`;
const float = (n: number) => `${String(n)}::double precision`;

export function cronSchedulesSql(cfg: EngramConfig = config): string {
  const d = cfg.decay;
  const sweep = [
    'now()',
    float(d.tauWorkingDays),
    float(d.tauLongTermDays),
    float(d.archiveThreshold),
    float(d.recencyWeight),
    float(d.accessWeight),
    float(d.importanceWeight),
    float(d.accessSaturation),
    `array[${STATIC_PREDICATES.map(literal).join(', ')}]::text[]`,
  ].join(', ');
  return `-- Generated by \`pnpm db:hosted-cron\` from packages/core/src/config. Do not edit.
-- Supabase-only (pg_cron isn't in the plain pgvector image). A repeatable file:
-- \`pnpm db:migrate:hosted\` re-applies it whenever it changes, and
-- cron.schedule replaces a job of the same name.
create extension if not exists pg_cron with schema pg_catalog;

-- Decay (SPEC §9.2): archive low-retention facts across every namespace.
select cron.schedule(
  'engram-decay-sweep',
  ${literal(cfg.schedules.decaySweep)},
  $cron$select engram.engram_decay_sweep(${sweep})$cron$
);

-- Demo cleanup (SPEC §11): delete expired demo namespaces.
select cron.schedule(
  'engram-demo-cleanup',
  ${literal(cfg.schedules.demoCleanup)},
  $cron$select engram.engram_cleanup_demo(now())$cron$
);
`;
}
