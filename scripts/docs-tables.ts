// The README's benchmark tables, generated from the committed report
// summaries (P10 decision 4), so the README can never disagree with
// bench/reports/. `pnpm docs:tables` rewrites the block between the markers;
// `--check` exits non-zero when it's stale (also asserted by a test).
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
export const START = '<!-- bench-tables:start (generated by `pnpm docs:tables`; do not edit) -->';
export const END = '<!-- bench-tables:end -->';

export const HEADLINE = { test: '2026-10-18-test', longmemeval: '2026-10-19-longmemeval' } as const;
export const AGREEMENT = 'agreement-2026-10-18-test+2026-10-19-longmemeval';
export const ABLATION = [
  {
    row: 'A',
    run: '2026-10-18-devlong-session',
    setup: 'Gemini 3.5 flash-lite + gemini-embedding-2',
  },
  { row: 'B', run: '2026-10-19-devlong-local-B', setup: 'qwen3.5:9b + gemini-embedding-2' },
  {
    row: 'C',
    run: '2026-10-18-devlong-local-C-counted',
    setup: 'qwen3.5:9b + embeddinggemma:300m (fully local)',
  },
  { row: 'C′', run: '2026-10-18-devlong-local-C-guard', setup: 'C, plus one extraction rule' },
] as const;

const CATEGORIES = [
  ['cross_session_recall', 'cross-session recall'],
  ['knowledge_update', 'knowledge update'],
  ['temporal_reasoning', 'temporal reasoning'],
  ['single_session_recall', 'single-session recall'],
  ['multi_hop', 'multi-hop'],
  ['abstention', 'abstention'],
] as const;
const MODES = ['buffer', 'rag', 'full_context', 'engram', 'engram_consolidated'] as const;

interface ModeRow {
  accuracy: number;
  n: number;
  recallAt8: number | null;
  requestsPerItem?: number;
  promptTokensPerItem?: number;
}
interface Summary {
  runId: string;
  model: string;
  judge: string;
  items: number;
  modes: Partial<Record<string, ModeRow>>;
  categories?: Record<string, Partial<Record<string, { accuracy: number; n: number }>>>;
}
interface Agreement {
  n: number;
  agreement: number;
  kappa: number | null;
  humanCorrect: number;
  humanIncorrect: number;
}

const read = (file: string): unknown =>
  JSON.parse(readFileSync(path.join(ROOT, 'bench/reports', file), 'utf8'));
const pct = (x: number) => `${String(Math.round(x * 100))}%`;

function accuracyTable(r: Summary): string[] {
  const modes = MODES.filter((m) => r.modes[m]);
  const lines = [
    `| category | n | ${modes.join(' | ')} |`,
    `|---|---|${modes.map(() => '---|').join('')}`,
  ];
  for (const [key, label] of CATEGORIES) {
    const byMode = r.categories?.[key];
    if (!byMode) continue;
    const n = Object.values(byMode)[0]?.n ?? 0;
    lines.push(
      `| ${label} | ${String(n)} | ${modes.map((m) => (byMode[m] ? pct(byMode[m].accuracy) : '—')).join(' | ')} |`,
    );
  }
  lines.push(
    `| **all** | ${String(r.items)} | ${modes
      .map((m) => {
        const row = r.modes[m];
        if (!row) return '—';
        return `**${pct(row.accuracy)}** (${String(Math.round(row.accuracy * row.n))}/${String(row.n)})`;
      })
      .join(' | ')} |`,
  );
  const recall = modes.flatMap((m) => {
    const v = r.modes[m]?.recallAt8;
    return typeof v === 'number' ? [`${m} ${pct(v)}`] : [];
  });
  return [
    ...lines,
    '',
    `recall@8: ${recall.join(', ')}. Report: \`bench/reports/${r.runId}.md\` (${r.model}; judge ${r.judge}).`,
  ];
}

/** The generated block, markers excluded. */
export function renderBenchTables(): string {
  const test = read(`${HEADLINE.test}.json`) as Summary;
  const lme = read(`${HEADLINE.longmemeval}.json`) as Summary;
  const agreement = read(`${AGREEMENT}.json`) as {
    pooled: Agreement;
    perRun: Record<string, Agreement>;
  };
  const costModes = MODES.filter((m) => test.modes[m] ?? lme.modes[m]);
  const cost = (r: Summary, field: 'requestsPerItem' | 'promptTokensPerItem') =>
    costModes.map((m) => {
      const v = r.modes[m]?.[field];
      return v === undefined
        ? 'pending'
        : field === 'requestsPerItem'
          ? v.toFixed(1)
          : v.toLocaleString('en');
    });
  const kappa = (a: Agreement) => (a.kappa === null ? 'undefined (one class)' : a.kappa.toFixed(2));
  const agreeRow = (label: string, a: Agreement) =>
    `| ${label} | ${String(a.n)} | ${String(a.humanCorrect)} / ${String(a.humanIncorrect)} | ${pct(a.agreement)} | ${kappa(a)} |`;
  const lines = [
    `### Test split (${String(test.items)} items)`,
    '',
    ...accuracyTable(test),
    '',
    `### LongMemEval-S (${String(lme.items)}-item stratified subset)`,
    '',
    ...accuracyTable(lme),
    '',
    '### Cost per item',
    '',
    `| | ${costModes.join(' | ')} |`,
    `|---|${costModes.map(() => '---|').join('')}`,
    `| test: requests / item | ${cost(test, 'requestsPerItem').join(' | ')} |`,
    `| test: prompt tokens / item | ${cost(test, 'promptTokensPerItem').join(' | ')} |`,
    `| LongMemEval: requests / item | ${cost(lme, 'requestsPerItem').join(' | ')} |`,
    `| LongMemEval: prompt tokens / item | ${cost(lme, 'promptTokensPerItem').join(' | ')} |`,
    '',
    'Requests count generate and embedding calls. Tokens are those sent to the generation model. Both include ingest, which Engram pays once per turn, not per question.',
    '',
    '### Judge agreement (blind hand labels)',
    '',
    '| sheet | labelled | correct / incorrect | agreement | Cohen’s κ |',
    '|---|---|---|---|---|',
    ...Object.entries(agreement.perRun).map(([run, a]) => agreeRow(run, a)),
    agreeRow('**pooled**', agreement.pooled),
    '',
    '### Local mode (dev-long, 40 items, one model swapped per row)',
    '',
    '| row | generation + embeddings | accuracy | recall@8 | knowledge update |',
    '|---|---|---|---|---|',
    ...ABLATION.map((a) => {
      const r = read(`${a.run}.json`) as Summary;
      const e = r.modes.engram;
      const ku = r.categories?.knowledge_update?.engram;
      return `| ${a.row} | ${a.setup} | ${e ? pct(e.accuracy) : '—'} | ${e && typeof e.recallAt8 === 'number' ? pct(e.recallAt8) : '—'} | ${ku ? `${String(Math.round(ku.accuracy * ku.n))}/${String(ku.n)}` : '—'} |`;
    }),
  ];
  return lines.join('\n');
}

/** The README with its generated block replaced (throws if the markers are missing). */
export function withTables(readme: string, block = renderBenchTables()): string {
  const i = readme.indexOf(START);
  const j = readme.indexOf(END);
  if (i < 0 || j < i) throw new Error('README.md has no bench-tables markers.');
  // Prettier would realign the tables and fight the generator, so the block is left to it.
  return `${readme.slice(0, i + START.length)}\n<!-- prettier-ignore-start -->\n\n${block}\n\n<!-- prettier-ignore-end -->\n${readme.slice(j)}`;
}

const isMain =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename);
if (isMain) {
  const file = path.join(ROOT, 'README.md');
  const current = readFileSync(file, 'utf8');
  const next = withTables(current);
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error('README.md bench tables are stale: run `pnpm docs:tables`.');
      process.exitCode = 1;
    } else console.log('README.md bench tables are current.');
  } else {
    writeFileSync(file, next);
    console.log(
      next === current
        ? 'README.md bench tables already current.'
        : 'README.md bench tables updated.',
    );
  }
}
